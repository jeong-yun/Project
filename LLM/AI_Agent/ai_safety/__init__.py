# AI Safety(안전성) 평가 기능을 모아둔 패키지입니다.
# english_word_maker 패키지와 동일한 방식으로,
# "기능 로직은 모듈에, 화면(UI)은 pages/ 페이지에" 분리합니다.
#
#   testcases.py : 카테고리별 공격 프롬프트(테스트 케이스) 정의
#   judge.py     : 대상 모델 호출 + LLM-as-judge 채점 로직
#   metrics.py   : 채점 결과를 방어율/점수로 집계 + 표(DataFrame) 변환
#   report.py    : 결과를 CSV/Excel 바이트로 변환(다운로드용)
#
# 이렇게 나누면 페이지 코드는 "흐름"만 담당하고,
# 실제 계산·모델 호출은 모듈에서 재사용할 수 있습니다.
